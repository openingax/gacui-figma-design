import assert from 'node:assert/strict';
import fs from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {createHash,randomUUID} from 'node:crypto';
import {createCollector} from '../support/server.mjs';
import {connect} from '../support/connect.mjs';
import * as client from '../support/client.mjs';
import {devices,revoke} from '../support/manage.mjs';

const directory=fs.mkdtempSync(join(tmpdir(),'gac-enrollment-'));
const settings={dataDir:join(directory,'data'),tokenHashes:[createHash('sha256').update(randomUUID()).digest('hex')],ticketSecret:randomUUID(),autoEnroll:true,maxDevices:2,maxDeviceBytes:4096};
let server=createCollector(settings);
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const port=server.address().port,endpoint='http://127.0.0.1:'+port;
const useDevice=name=>{
 process.env.GAC_SUPPORT_HOME=join(directory,name,'state');
 process.env.GAC_SUPPORT_CONFIG=join(directory,name,'config.json');
};
try{
 useDevice('product');
 const first=await connect(endpoint);
 assert.equal(first.state,'connected');assert.equal(first.enrolled,true);assert.match(first.notice,/docs\/support\/README.md/);
 const product=client.config();
 if(process.platform!=='win32')assert.equal(fs.statSync(process.env.GAC_SUPPORT_CONFIG).mode&0o777,0o600);
 assert.ok(!JSON.stringify(first).includes(product.token));
 assert.equal(client.status().collection,'tuning');
 assert.equal(client.status().autoUpload,true);
 const again=await connect(endpoint);
 assert.equal(again.deviceId,product.installationId);assert.equal(again.enrolled,false);assert.equal(again.notice,undefined);
 client.trace(directory,{kind:'agent-turn',payload:{input:'synthetic',output:'synthetic response',model:null}});
 await client.flush();assert.equal(client.pending().length,0);
 const registry=fs.readFileSync(join(directory,'data/devices.json'),'utf8');
 assert.ok(!registry.includes(product.token));
 assert.equal(Object.keys(JSON.parse(registry)).length,1);
 useDevice('ui');
 await connect(endpoint);const ui=client.config();assert.notEqual(ui.token,product.token);assert.notEqual(ui.installationId,product.installationId);
 await assert.rejects(client.request('/v1/enroll',{installationId:product.installationId,tokenHash:createHash('sha256').update(ui.token).digest('hex')}),/HTTP_409/);
 await assert.rejects(client.request('/v1/tickets',{taskId:client.taskId(directory)},{endpoint,token:'unknown-token'}),/HTTP_401/);
 client.trace(directory,{kind:'tool-call',payload:{output:'x'.repeat(5000)}});
 await assert.rejects(client.flush(),/HTTP_507/);assert.equal(client.pending().length,1);
 const quota=await fetch(endpoint+'/v2/events',{method:'POST',headers:{'Content-Type':'application/json',Authorization:'Bearer '+ui.token},body:JSON.stringify({events:client.pending()})});
 assert.equal(quota.status,507);assert.equal((await quota.json()).error,'device_quota');
 client.setAutoUpload(false);
 let requests=0;server.on('request',()=>requests++);
 assert.equal((await connect(endpoint)).state,'disabled');assert.equal(requests,0);
 useDevice('self-hosted');
 fs.mkdirSync(join(directory,'self-hosted'),{recursive:true});
 fs.writeFileSync(process.env.GAC_SUPPORT_CONFIG,JSON.stringify({endpoint,token:'s'.repeat(64)}),{mode:0o600});
 const before=requests,selfHosted=await connect(endpoint);
 assert.equal(selfHosted.state,'self-managed');assert.equal(selfHosted.autoUpload,false);assert.equal(requests,before);assert.equal(client.status().autoUpload,false);
 useDevice('third');
 await assert.rejects(connect(endpoint),/HTTP_503/);assert.equal(client.status().autoUpload,false);
 const third=client.config();await assert.rejects(connect(endpoint),/HTTP_503/);assert.equal(client.config().token,third.token);
 await new Promise(resolve=>server.close(resolve));
 server=createCollector(settings);await new Promise(resolve=>server.listen(port,'127.0.0.1',resolve));
 useDevice('product');assert.equal((await connect(endpoint)).deviceId,product.installationId);
 await new Promise(resolve=>server.close(resolve));
 assert.equal(devices(settings.dataDir).length,2);assert.equal(revoke(settings.dataDir,product.installationId).restartRequired,true);
 server=createCollector(settings);await new Promise(resolve=>server.listen(port,'127.0.0.1',resolve));
 await assert.rejects(connect(endpoint),/HTTP_409/);assert.equal(client.config().token,product.token);
 assert.equal(devices(settings.dataDir).find(d=>d.id===product.installationId).revoked,true);
 console.log('PASS enrollment: unique credentials, automatic verification/upload, retry, restart, revocation, quota, capacity, self-managed config and explicit disable');
}finally{await new Promise(resolve=>server.close(resolve));fs.rmSync(directory,{recursive:true,force:true});}
